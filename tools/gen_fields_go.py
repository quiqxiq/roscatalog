#!/usr/bin/env python3
"""Buat file Go per-menu dari mikrotik_inspect/SOURCE.md.

Hasil: folder `fields/` berisi package `fields`, satu file per menu besar,
misalnya fields/ip.go, fields/ppp.go, fields/queue.go, fields/interface.go.
Pemakaian: fields.IPAddressRow.

Tooling maintainer saja; file hasil di-commit supaya konsumen tidak butuh
Python atau akses router.
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "mikrotik_inspect" / "SOURCE.md"
OUTDIR = ROOT / "fields"


def parse_blocks(text: str) -> dict[str, list[str]]:
    blocks: dict[str, list[str]] = defaultdict(list)
    current = ""
    buf: list[str] = []
    inside = False
    for line in text.splitlines():
        m = re.match(r"^### `([^`]+)`", line)
        if m:
            current = m.group(1)
            continue
        if line.strip() == "```go" and current:
            inside = True
            buf = []
            continue
        if inside and line.strip() == "```":
            blocks[current].append("\n".join(buf).strip("\n"))
            inside = False
            continue
        if inside:
            buf.append(line)
    return blocks


def menu_of(path: str) -> str:
    first = path.strip("/").split("/")[0] if path.strip("/") else "root"
    return re.sub(r"[^a-z0-9]", "", first.lower()) or "root"


def main() -> None:
    blocks = parse_blocks(SOURCE.read_text(encoding="utf-8"))
    groups: dict[str, list[tuple[str, list[str]]]] = defaultdict(list)
    for path, blks in blocks.items():
        groups[menu_of(path)].append((path, blks))

    OUTDIR.mkdir(exist_ok=True)
    written = 0
    for menu in sorted(groups):
        items = sorted(groups[menu])
        out = [
            "// Code generated by tools/gen_fields_go.py; DO NOT EDIT.",
            "// Sumber: mikrotik_inspect/SOURCE.md (inspect + print router + katalog).",
            "",
            "package fields",
            "",
        ]
        for i, (path, blks) in enumerate(items):
            if i:
                out.append("")
            out.append("// " + "=" * 72)
            out.append(f"// Menu {path}")
            out.append("// " + "=" * 72)
            out.append("")
            for blk in blks:
                out.append(blk)
                out.append("")
        target = OUTDIR / f"{menu}.go"
        target.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
        written += 1

    print(f"ditulis: {written} file Go per-menu, {sum(len(v) for v in blocks.values())} struct")


if __name__ == "__main__":
    main()
