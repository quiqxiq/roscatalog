#!/usr/bin/env python3
"""Buat zz_catalog_enrich.go: tambah flag print dan aksi yang kurang.

Sumber: catalog_dump.json (resource katalog) + inspect JSON (perintah tersedia).
File zz_* dipilih supaya init()-nya jalan setelah init() katalog lain.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_commands import PRINT_VALUE_ARGS, READ_VERBS  # noqa: E402

INSPECT = ROOT / "mikrotik_inspect"
OUT = ROOT / "zz_catalog_enrich.go"
SKIP = {"_index.json", "print_fields.json", "catalog_dump.json"}


def go_str(s: str) -> str:
    return json.dumps(s)


def str_list(items: list[str]) -> str:
    return "[]string{" + ", ".join(go_str(x) for x in items) + "}"


def main() -> None:
    idx = json.loads((INSPECT / "_index.json").read_text(encoding="utf-8"))
    by_path = {f["path"]: f["file"] for f in idx["files"]}
    catalog = json.loads((INSPECT / "catalog_dump.json").read_text(encoding="utf-8"))

    blocks: list[str] = []
    count = 0
    for r in catalog:
        fname = by_path.get(r["path"])
        if not fname or not (INSPECT / fname).exists():
            continue
        data = json.loads((INSPECT / fname).read_text(encoding="utf-8"))
        cmds = {
            k: v for k, v in data.items()
            if isinstance(v, dict) and v.get("_type") == "cmd"
        }
        have = {a["name"] for a in r["actions"]}

        print_cmd = cmds.get("print")
        flags: list[str] = []
        values: list[str] = []
        if print_cmd:
            for name, spec in print_cmd.items():
                if name == "_type" or not isinstance(spec, dict) or spec.get("_type") != "arg":
                    continue
                (values if name in PRINT_VALUE_ARGS else flags).append(name)

        set_args: list[str] = []
        for a in r["actions"]:
            if a["name"] == "set":
                set_args = a.get("optional", [])
                break

        lines: list[str] = []
        if flags:
            mode_ok = 'r.Views[i].Mode == "oneshot" || r.Views[i].Mode == "interval" || r.Views[i].Mode == "follow"'
            lines.append(f"\t\tfor i := range r.Views {{\n\t\t\tif {mode_ok} {{\n\t\t\t\tr.Views[i].AllowedFlags = {str_list(flags)}\n\t\t\t}}\n\t\t}}")
        if print_cmd and "print" not in have:
            lines.append(
                f"\t\tr.ReadDo(\"print\", {str_list(flags)}, nil, {str_list(values)}, "
                + go_str("perintah baca print dari inspect") + ")"
            )
        if "comment" in cmds and "comment" not in have:
            lines.append(
                "\t\tr.Do(\"comment\", SelNumbers, nil, "
                + str_list(["comment"]) + ", false, \"\")"
            )
        if "unset" in cmds and "unset" not in have and set_args:
            lines.append(
                "\t\tr.Do(\"unset\", SelNumbers, nil, " + str_list(set_args) + ", false, \"\")"
            )
        if "reset" in cmds and "reset" not in have and set_args:
            lines.append(
                "\t\tr.Do(\"reset\", SelNumbers, nil, " + str_list(set_args)
                + ", true, \"kembalikan properti ke nilai bawaan\")"
            )
        if "export" in cmds and "export" not in have:
            exp_args = [a for a in cmds["export"] if a != "_type" and isinstance(cmds["export"][a], dict)]
            keep = [a for a in exp_args if a in {"file", "compact", "terse", "verbose", "hide-sensitive", "show-sensitive"}]
            lines.append(
                "\t\tr.Do(\"export\", SelNone, nil, " + str_list(keep) + ", false, \"\")"
            )
        if not lines:
            continue
        blocks.append(
            f"\tenrich({go_str(r['id'])}, func(r *Resource) {{\n"
            + "\n".join(lines)
            + "\n\t})"
        )
        count += 1

    out = [
        "// Code generated by tools/gen_catalog_enrich.py; DO NOT EDIT.",
        "// Sumber: catalog_dump.json + mikrotik_inspect/*.json.",
        "",
        "package roscatalog",
        "",
        "func init() {",
        "\tenrich := func(id string, fn func(*Resource)) {",
        "\t\tif r, ok := Lookup(id); ok {",
        "\t\t\tfn(r)",
        "\t\t}",
        "\t}",
    ]
    out.extend(blocks)
    out.append("}")
    OUT.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"ditulis: {OUT} ({count} resource)")


if __name__ == "__main__":
    main()
