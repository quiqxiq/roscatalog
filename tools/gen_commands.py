#!/usr/bin/env python3
"""Buat package `commands` berisi semua perintah/argumen dari inspect JSON.

Satu file Go per menu, misalnya commands/ip.go, commands/ppp.go.
Ini data mentah hasil /console/inspect, bukan katalog kurasi.
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_source_md import ACRONYMS  # noqa: E402

INSPECT = ROOT / "mikrotik_inspect"
OUTDIR = ROOT / "commands"
SKIP = {"_index.json", "print_fields.json", "catalog_dump.json"}

READ_VERBS = {"print", "get", "find", "recursive-print", "monitor", "monitor-traffic"}
DESTRUCTIVE_VERBS = {
    "remove", "reset", "shutdown", "reboot", "flush", "erase",
    "restore", "import", "uninstall",
}
PRINT_VALUE_ARGS = {
    "file", "from", "where", "interval", "on-event", "group-by",
    "order-by", "proplist", "oid", "value-list",
}


def go_name(path: str, used: set[str]) -> str:
    parts = []
    for seg in (s for s in path.split("/") if s):
        key = seg.lower()
        if key in ACRONYMS:
            parts.append(ACRONYMS[key])
        else:
            parts.append(seg[:1].upper() + seg[1:])
    base = re.sub(r"[^A-Za-z0-9_]", "", "".join(parts)) or "Menu"
    name = base
    if name in used:
        i = 2
        while f"{name}{i}" in used:
            i += 1
        name = f"{name}{i}"
    used.add(name)
    return name


def menu_of(path: str) -> str:
    first = path.strip("/").split("/")[0] if path.strip("/") else "root"
    return re.sub(r"[^a-z0-9]", "", first.lower()) or "root"


def main() -> None:
    index = json.loads((INSPECT / "_index.json").read_text(encoding="utf-8"))
    by_file = {f["file"]: f for f in index["files"]}
    used: set[str] = set()
    groups: dict[str, list[tuple[str, str, list[str]]]] = defaultdict(list)
    registry: list[tuple[str, str]] = []

    for p in sorted(INSPECT.glob("*.json")):
        if p.name in SKIP:
            continue
        f = by_file.get(p.name)
        if not f:
            continue
        path = f["path"]
        data = json.loads(p.read_text(encoding="utf-8"))
        cmds = {
            k: v for k, v in data.items()
            if isinstance(v, dict) and v.get("_type") == "cmd"
        }
        if not cmds:
            continue
        var = go_name(path, used)
        lines = [f"var {var} = []Command{{"]
        for verb in sorted(cmds):
            args = []
            for name, spec in cmds[verb].items():
                if name == "_type" or not isinstance(spec, dict):
                    continue
                if spec.get("_type") != "arg":
                    continue
                flag = verb == "print" and name not in PRINT_VALUE_ARGS
                desc = re.sub(r"\s+", " ", spec.get("desc", "")).strip().replace('"', "'")
                args.append(f'\t\t{{Name: {json.dumps(name)}, Flag: {str(flag).lower()}, Note: {json.dumps(desc)}}},')
            read = str(verb in READ_VERBS).lower()
            destructive = str(verb in DESTRUCTIVE_VERBS).lower()
            lines.append(f"\t{{Verb: {json.dumps(verb)}, Read: {read}, Destructive: {destructive},")
            lines.append("\t\tArgs: []Arg{")
            lines.extend(args)
            lines.append("\t\t},")
            lines.append("\t},")
        lines.append("}")
        groups[menu_of(path)].append((path, var, lines))
        registry.append((path, var))

    OUTDIR.mkdir(exist_ok=True)
    header = [
        "// Code generated by tools/gen_commands.py; DO NOT EDIT.",
        "// Sumber: mikrotik_inspect/*.json (/console/inspect). Data mentah, bukan katalog kurasi.",
        "",
        "package commands",
        "",
        "type Arg struct {",
        "\tName  string",
        "\tFlag  bool // true = dikirim sebagai =name= (bukan =name=value)",
        "\tNote  string",
        "}",
        "",
        "type Command struct {",
        "\tVerb        string",
        "\tRead        bool",
        "\tDestructive bool",
        "\tArgs        []Arg",
        "}",
        "",
    ]
    (OUTDIR / "types.go").write_text("\n".join(header), encoding="utf-8")

    for menu in sorted(groups):
        out = list(header[:5])
        for path, var, lines in sorted(groups[menu]):
            out.append(f"// Path: {path}")
            out.extend(lines)
            out.append("")
        (OUTDIR / f"{menu}.go").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")

    reg = list(header[:5])
    reg.append("// ByPath memetakan path RouterOS ke daftar perintah.")
    reg.append("var ByPath = map[string][]Command{")
    for path, var in sorted(registry):
        reg.append(f'\t{json.dumps(path)}: {var},')
    reg.append("}")
    (OUTDIR / "registry.go").write_text("\n".join(reg).rstrip() + "\n", encoding="utf-8")

    print(f"ditulis: {len(groups)} file per-menu + types.go + registry.go, {len(registry)} path")


if __name__ == "__main__":
    main()
